def test_nemo_uses_only_the_builtin_flow_name():
    """A custom flow name makes NeMo silently disable every tool rail."""
    config = export_nemo(RULES).config
    assert config["rails"]["tool_output"]["flows"] == [TOOL_OUTPUT_FLOW]


def test_nemo_declares_allow_listed_tools():
    config = export_nemo(RULES).config
    names = [
        tool["function"]["name"]
        for model in config["models"]
        for tool in model.get("parameters", {}).get("tools", [])
    ]
    assert "query_order" in names
    assert "get_logistics" in names


def test_nemo_reports_forbid_tool_as_unsupported():
    """NeMo has no forbid-list primitive -- it must say so, not fake it."""
    result = export_nemo(RULES)
    assert any("forbid_tool" in item for item in result.unsupported)


def test_nemo_emits_no_custom_colang():
    from agentguard.exporters.nemo import render_nemo

    text = render_nemo(RULES)
    assert "define flow" not in text
    assert "tool call validation" in text


def test_nemo_omits_rail_when_nothing_to_allow():
    only_forbid = Rule(name="f", then=Then(forbid_tool=("x",)), where=Where(True, True))
    config = export_nemo([only_forbid]).config
    assert "tool_output" not in config["rails"]


