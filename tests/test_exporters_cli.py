def _workspace(tmp_path: Path) -> Path:
    root = tmp_path / "ws"
    assert main(["init", "--dir", str(root)]) == 0
    return root


def test_cli_init_scaffolds(tmp_path):
    root = _workspace(tmp_path)
    assert (root / "rules" / "refund-safety.yaml").exists()
    # Idempotency ships as its own file because `when` gates a whole rule --
    # see test_scaffold_keeps_idempotency_out_of_the_when_gate.
    assert (root / "rules" / "payment-idempotency.yaml").exists()
    # traces/ holds the clean baseline; the incident lives in examples/.
    assert (root / "traces" / "baseline-clean.json").exists()
    assert (root / "examples" / "refund_incident.json").exists()


def test_scaffold_keeps_idempotency_out_of_the_when_gate(tmp_path):
    """The scaffold is the first thing every user copies.

    It used to nest `idempotent` under `when.intent_any`, which meant the
    duplicate-refund check only ran on turns containing a trigger word --
    including in the shipped `rules/`.  Guard the shape at the source.
    """
    from agentguard.rules import load_rules, validate_rules

    root = _workspace(tmp_path)
    rules = load_rules(root / "rules")

    gated = [r.name for r in rules if r.then.idempotent and not r.when.always]
    assert not gated, f"scaffold gates idempotency behind `when`: {gated}"

    # And the scaffold must not warn about anything else either.
    assert validate_rules(rules) == []


def test_scaffold_stops_a_duplicate_refund(tmp_path):
    """Behavioural check on the generated workspace, not just its shape."""
    from agentguard.executors.runtime import RuntimeGuard
    from agentguard.idempotency import MemoryStore

    root = _workspace(tmp_path)
    guard = RuntimeGuard.from_rules(root / "rules", store=MemoryStore())

    for _ in range(2):
        decision = guard.check(
            "refund_order", {"order_id": "A1001"}, user="那我再等等", turn=3
        )
        if decision.allowed:
            guard.record("refund_order", {"order_id": "A1001"})

    assert decision.code == "duplicate_transaction"


def test_scaffold_incident_exercises_both_shipped_rules(tmp_path):
    """Both scaffolded rules must actually fire on the scaffolded incident.

    `payment-idempotency.yaml` ships as its own file with a dedicated
    explanation, so a user reasonably expects `run --traces examples` to show
    it working.  It only does if the incident calls the same tool twice with
    the same key -- and for a while it did not, which made the idempotency
    file look like dead weight.
    """
    from agentguard.executors.ci import run_gate

    root = _workspace(tmp_path)
    outcome = run_gate(root / "rules", root / "examples", fail_on="critical")
    kinds = {v.kind for _t, results in outcome.runs for r in results for v in r.violations}

    assert "forbidden_tool" in kinds, kinds
    assert "duplicate_transaction" in kinds, (
        "the scaffolded incident never triggers the idempotency rule, so the "
        f"shipped payment-idempotency.yaml cannot be demonstrated: {kinds}"
    )


def test_scaffold_incident_reports_each_violation_for_a_real_reason(tmp_path):
    """No violation may be a `tool_not_allowed` false positive.

    That kind means "a name was not on a closed list" -- if it ever shows up
    for the scaffold, the rules have drifted back to the shape that reported
    the wrong reason for a bad call.
    """
    from agentguard.executors.ci import run_gate

    root = _workspace(tmp_path)
    outcome = run_gate(root / "rules", root / "examples", fail_on="critical")
    kinds = {v.kind for _t, results in outcome.runs for r in results for v in r.violations}
    assert "tool_not_allowed" not in kinds, kinds


