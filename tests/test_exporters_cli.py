"""Tests for the ecosystem exporters and the CLI."""

from __future__ import annotations

import json
from pathlib import Path

from agentguard.cli import main
from agentguard.exporters.nemo import TOOL_OUTPUT_FLOW, export_nemo
from agentguard.exporters.promptfoo import export_promptfoo, render_promptfoo
from agentguard.rules import IdempotencyRule, Rule, Then, Where

RULES = [
    Rule(
        name="refund-safety",
        then=Then(
            forbid_tool=("refund_order",),
            allow_tool=("query_order", "get_logistics"),
            require_tool=("query_order",),
            max_tool_calls=6,
            idempotent=(IdempotencyRule("refund_order", "${order_id}"),),
        ),
        where=Where(ci=True, runtime=True),
        severity="critical",
    ),
    Rule(
        name="ci-only",
        then=Then(forbid_tool=("danger",)),
        where=Where(ci=True, runtime=False),
    ),
]


# --------------------------------------------------------------------------- #
# promptfoo exporter
# --------------------------------------------------------------------------- #
def test_promptfoo_forbidden_tool_maps_to_inverse_assertion():
    config = export_promptfoo(RULES).config
    asserts = config["tests"][0]["assert"]
    types = [a["type"] for a in asserts]
    assert "not-trajectory:tool-used" in types

    forbidden = next(a for a in asserts if a["type"] == "not-trajectory:tool-used")
    assert forbidden["value"] == "refund_order"


def test_promptfoo_required_tool_is_positive_assertion():
    config = export_promptfoo(RULES).config
    asserts = config["tests"][0]["assert"]
    positive = [a for a in asserts if a["type"] == "trajectory:tool-used"]
    assert any(a["value"] == "query_order" for a in positive)


def test_promptfoo_emits_call_budget():
    config = export_promptfoo(RULES).config
    asserts = config["tests"][0]["assert"]
    budget = [a for a in asserts if a["type"] == "trajectory:step-count"]
    assert budget and budget[0]["value"]["max"] == 6


def test_promptfoo_renders_to_yaml():
    text = render_promptfoo(RULES)
    assert "not-trajectory:tool-used" in text
    assert "Generated by" in text


