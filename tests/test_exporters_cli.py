def test_cli_learn_preview_then_apply(tmp_path):
    root = _workspace(tmp_path)
    trace = root / "examples" / "refund_incident.json"
    out = root / "rules" / "learned.yaml"

    assert main(["learn", "--trace", str(trace), "--out", str(out)]) == 0
    assert not out.exists()  # preview must not write

    assert (
        main(["learn", "--trace", str(trace), "--out", str(out), "--apply"]) == 0
    )
    assert out.exists()
    assert "forbid_tool" in out.read_text(encoding="utf-8")


